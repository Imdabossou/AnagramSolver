#!/usr/bin/env python3
"""Draws the launcher icon layers from the same design as icon.svg.

Android vectors can't hold text, so the "A" and "1" are turned into paths
from Liberation Serif Bold. Run it from the repo root after changing the design:
    python3 android/tools/make-icon.py
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

FONT = "/usr/share/fonts/liberation/LiberationSerif-Bold.ttf"
RES = Path(__file__).resolve().parent.parent / "app/src/main/res"
S = 0.16                    # icon.svg units -> dp
CX, CY = 256, 250           # tile centre in icon.svg

def to_dp(x, y):
    return 54 + (x - CX) * S, 54 + (y - CY) * S

def glyph(font, ch, size, x_mid, baseline):
    gs = font.getGlyphSet()
    name = font.getBestCmap()[ord(ch)]
    k = size / font["head"].unitsPerEm
    left = x_mid - gs[name].width * k / 2
    pen = SVGPathPen(gs, lambda v: f"{v:.2f}")
    ox, oy = to_dp(left, baseline)
    gs[name].draw(TransformPen(pen, (k * S, 0, 0, -k * S, ox, oy)))
    return pen.getCommands()

def rrect(x, y, w, h, r):
    (x0, y0), (x1, y1), r = to_dp(x, y), to_dp(x + w, y + h), r * S
    f = lambda v: f"{v:.2f}"
    return (f"M{f(x0 + r)},{f(y0)}H{f(x1 - r)}A{f(r)},{f(r)} 0 0 1 {f(x1)},{f(y0 + r)}"
            f"V{f(y1 - r)}A{f(r)},{f(r)} 0 0 1 {f(x1 - r)},{f(y1)}H{f(x0 + r)}"
            f"A{f(r)},{f(r)} 0 0 1 {f(x0)},{f(y1 - r)}V{f(y0 + r)}A{f(r)},{f(r)} 0 0 1 {f(x0 + r)},{f(y0)}Z")

font = TTFont(FONT)
edge = rrect(116, 108, 280, 296, 36)
face = rrect(116, 96, 280, 284, 36)
letters = glyph(font, "A", 230, 256, 320) + glyph(font, "1", 54, 352, 358)

head = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n')
p = lambda d, attrs: f'    <path {attrs}\n        android:pathData="{d}" />\n'

(RES / "drawable/ic_launcher_foreground.xml").write_text(
    "<!-- Generated by android/tools/make-icon.py -->\n" + head
    + p(edge, 'android:fillColor="#D9C08A"')
    + p(face, 'android:fillColor="#F3E2B8"')
    + p(letters, 'android:fillColor="#1D2321"') + "</vector>\n")
# Themed icons use alpha only, so the letters are holes cut through the tile.
(RES / "drawable/ic_launcher_monochrome.xml").write_text(
    "<!-- Generated by android/tools/make-icon.py -->\n" + head
    + p(face + letters, 'android:fillColor="#FFFFFF" android:fillType="evenOdd"') + "</vector>\n")
